# User-added poses live here; they win over builtins on id collisions.
_CUSTOM_PATH = Path(__file__).resolve().parents[3] / "skills_builtin" / "shot_poses.json"


def list_builtin_poses() -> list[dict[str, Any]]:
    """[{id, name, category, source}] — frontmatter only, never full postures."""
    out = [
        {"id": p["id"], "name": p["name"], "category": "authored", "source": "builtin"}
        for p in _POSES
    ]
    custom = _load_custom()
    known = {p["id"] for p in out}
    for p in custom:
        if p.get("id") in known:
            for row in out:
                if row["id"] == p["id"]:
                    row["name"] = p.get("name", row["name"])
                    row["source"] = "custom"
        else:
            out.append(
                {
                    "id": p["id"],
                    "name": p.get("name", p["id"]),
                    "category": p.get("category", "custom"),
                    "source": "custom",
                }
            )
    return out


def get_builtin_pose(pose_id: str) -> dict[str, Any] | None:
    for p in _load_custom():
        if p.get("id") == pose_id:
            posture = p.get("posture")
            if isinstance(posture, dict):
                return posture
    for p in _POSES:
        if p["id"] == pose_id:
            return dict(p["posture"])
    return None


def _load_custom() -> list[dict[str, Any]]:
    try:
        raw = json.loads(_CUSTOM_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return []
    return raw if isinstance(raw, list) else []
